def _parse_sse(response):
    """Parse a streaming response into (tokens, sources_or_none, error)."""
    tokens = []
    sources = None
    error = None
    for part in response.streaming_content:
        text = part.decode("utf-8")
        for block in text.split("\n\n"):
            lines = block.strip().splitlines()
            event = next((line[6:].strip() for line in lines if line.startswith("event:")), None)
            data = next((line[5:].strip() for line in lines if line.startswith("data:")), None)
            if event == "token":
                tokens.append(json.loads(data)["text"])
            elif event == "sources":
                sources = json.loads(data)
            elif event == "error":
                error = json.loads(data)
    return tokens, sources, error


def _upload(file_payload):
    """Upload a document and wait for eager ingestion to finish."""
    response = client.post("/api/documents/", {"file": file_payload}, format="multipart")
    assert response.status_code == 202
    document_id = response.json()["id"]
    document = Document.objects.get(pk=document_id)
    assert document.status == "indexed"
    return document


def test_upload_to_indexed_pipeline_for_every_format():
    """Upload → ingestion → indexed, for the four accepted formats."""
    for make_file in FORMAT_FILES.values():
        document = _upload(make_file())
        assert document.chunks.count() >= 1


def test_question_streams_answer_citing_the_uploaded_document():
    """Question → streamed answer with sources from the document."""
    document = _upload(_make_file("guide.txt"))
    response = client.post("/api/query/", {"question": "How does retrieval work?"}, format="json")
    assert response.status_code == 200
    assert response["Content-Type"].startswith("text/event-stream")
    tokens, sources, error = _parse_sse(response)
    assert error is None
    assert "".join(tokens).strip()
    assert sources is not None
    source_document_ids = {source["document"]["id"] for source in sources["sources"]}
    assert source_document_ids == {document.pk}


def test_deletion_removes_document_and_future_retrieval():
    """Deletion → document and chunks gone, retrieval returns nothing."""
    document = _upload(_make_file("guide.txt"))
    assert Chunk.objects.filter(document=document).exists()

    response = client.delete(f"/api/documents/{document.pk}/")
    assert response.status_code in (200, 204)
    assert not Document.objects.filter(pk=document.pk).exists()
    assert not Chunk.objects.filter(document_id=document.pk).exists()

    query = client.post("/api/query/", {"question": "How does retrieval work?"}, format="json")
    _, sources, _ = _parse_sse(query)
    assert sources is not None
    assert sources["sources"] == []


def test_reupload_replaces_chunks_without_duplicates():
    """Re-upload of the same file → chunks replaced, no duplicates."""
    first = _upload(_make_file("guide.txt"))
    second = _upload(_make_file("guide.txt"))
    assert second.pk != first.pk
    assert Document.objects.count() == 2
    chunk_count = Chunk.objects.count()
    assert chunk_count == first.chunks.count() + second.chunks.count()
    assert Chunk.objects.values("document").distinct().count() == 2
